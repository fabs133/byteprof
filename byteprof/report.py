"""Render a Breakdown as Markdown and JSON (pure)."""

from __future__ import annotations

import json
from dataclasses import asdict
from typing import Any

from .timing import Breakdown, PhaseBreakdown


def _phase_rows(phase: PhaseBreakdown, generated_bytes: int, per_byte: bool) -> list[str]:
    rows = []
    total = phase.step_ms or 1e-9
    items = sorted(phase.components.items(), key=lambda kv: -kv[1].total_ms)
    for name, st in items:
        per_b = f"{st.total_ms / generated_bytes:.3f}" if per_byte and generated_bytes else "-"
        rows.append(
            f"| {name} | {st.calls} | {st.total_ms:.1f} | {100 * st.total_ms / total:.1f}% "
            f"| {st.mean_ms:.3f} | {per_b} |"
        )
    un = phase.unattributed_ms
    per_b = f"{un / generated_bytes:.3f}" if per_byte and generated_bytes else "-"
    rows.append(f"| _unattributed (inside step)_ | - | {un:.1f} | {100 * un / total:.1f}% | - | {per_b} |")
    return rows


def render_markdown(bd: Breakdown, meta: dict[str, Any], baseline_wall_ms: float | None) -> str:
    head = "| component | calls | total ms | % of phase | mean ms/call | ms/gen. byte |"
    sep = "|---|---:|---:|---:|---:|---:|"
    lines = [
        f"# Profile: {meta.get('model_id', '?')}",
        "",
        f"- runs: {bd.runs}, generated bytes (total): {bd.generated_bytes}",
        f"- wall time (hooked): {bd.wall_ms:.1f} ms, throughput {bd.bytes_per_second:.1f} bytes/s",
    ]
    if baseline_wall_ms is not None and baseline_wall_ms > 0:
        overhead = 100 * (bd.wall_ms - baseline_wall_ms) / baseline_wall_ms
        lines.append(f"- wall time (no hooks, same workload): {baseline_wall_ms:.1f} ms -> hook overhead {overhead:+.1f}%")
    lines += [
        f"- prefill steps: {bd.prefill.steps} ({bd.prefill.step_ms:.1f} ms), "
        f"decode steps: {bd.decode.steps} ({bd.decode.step_ms:.1f} ms)",
        f"- decode: {bd.decode_ms_per_byte:.3f} ms per generated byte",
        f"- outside step forwards (generate loop, sampling, host): {bd.outside_step_ms:.1f} ms",
    ]
    if bd.generated_bytes and bd.decode.steps:
        lines.append(f"- decode steps per generated byte: {bd.decode.steps / bd.generated_bytes:.3f}")
    lines += ["", "## Decode", "", head, sep, *_phase_rows(bd.decode, bd.generated_bytes, True)]
    lines += ["", "## Prefill", "", head, sep, *_phase_rows(bd.prefill, bd.generated_bytes, False)]
    if bd.outside_step_components:
        lines += ["", "## Component calls outside step forwards", "", "| component | calls | total ms |", "|---|---:|---:|"]
        for name, st in sorted(bd.outside_step_components.items()):
            lines.append(f"| {name} | {st.calls} | {st.total_ms:.1f} |")
    if bd.warnings:
        lines += ["", "## Warnings", ""] + [f"- {w}" for w in bd.warnings]
    lines += ["", "## Environment", "", "```json", json.dumps(meta, indent=2, default=str), "```", ""]
    return "\n".join(lines)


def to_json(bd: Breakdown, meta: dict[str, Any], baseline_wall_ms: float | None) -> str:
    data = asdict(bd)
    data["derived"] = {
        "outside_step_ms": bd.outside_step_ms,
        "decode_ms_per_byte": bd.decode_ms_per_byte,
        "bytes_per_second": bd.bytes_per_second,
        "prefill_unattributed_ms": bd.prefill.unattributed_ms,
        "decode_unattributed_ms": bd.decode.unattributed_ms,
        "baseline_wall_ms": baseline_wall_ms,
    }
    data["meta"] = meta
    return json.dumps(data, indent=2, default=str)


def render_optimized_markdown(rows: list[dict[str, Any]], meta: dict[str, Any], warnings: list[str]) -> str:
    """Report for optimize != "none": wall time only, no component breakdown (pure)."""
    total_bytes = sum(r["new_bytes"] for r in rows)
    total_ms = sum(r["ms"] for r in rows)
    opt = meta.get("optimization", {})
    lines = [
        f"# Profile (optimized: {opt.get('variant', '?')}): {meta.get('model_id', '?')}",
        "",
        "**No component breakdown exists for optimized runs**: forward hooks are bypassed by CUDA graphs "
        "and events cannot be recorded during capture, so the hooked phase is skipped.",
        "",
        f"- runs: {len(rows)}, generated bytes (total): {total_bytes}",
    ]
    if total_ms and total_bytes:
        lines += [
            f"- wall time (no hooks): {total_ms:.1f} ms, throughput {1000 * total_bytes / total_ms:.1f} bytes/s",
            f"- decode-equivalent: {total_ms / total_bytes:.3f} ms per generated byte "
            "(= wall time / new bytes, includes prefill; not a hooked decode figure)",
        ]
    secs = ", ".join(f"{t:.1f}" for t in opt.get("warmup_pass_seconds", []))
    lines += [
        f"- warmup pass times (s, first pass includes compile/capture): {secs}",
        f"- GPU memory allocated delta vs eager: {opt.get('gpu_mem_allocated_delta_mib', 0):.0f} MiB, "
        f"peak {opt.get('gpu_mem_peak_mib', 0):.0f} MiB",
        f"- details: {opt.get('details', '')}",
        "",
        "## Correctness vs eager (first divergence, byte index; `-` = identical)",
        "",
        "| run | prompt | new bytes | ms | first divergence | ref bytes | out bytes |",
        "|---:|---|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        d = "-" if r["first_divergence"] is None else str(r["first_divergence"])
        lines.append(f"| {r['run']} | {r['prompt_id']} | {r['new_bytes']} | {r['ms']:.1f} | {d} | {r['ref_len']} | {r['out_len']} |")
    instr_rows = [r["instr"] for r in rows if "instr" in r]
    if instr_rows:
        lines += ["", "## Instrumentation (opt-in; these runs are NOT final throughput)", ""]
        keys = sorted({k for i in instr_rows for k in i})
        lines += ["| " + " | ".join(keys) + " |", "|" + "---:|" * len(keys)]
        for i in instr_rows:
            lines.append("| " + " | ".join(f"{i[k]:.3f}" if isinstance(i.get(k), float) else str(i.get(k, "")) for k in keys) + " |")
    if warnings:
        lines += ["", "## Warnings", ""] + [f"- {w}" for w in warnings]
    lines += ["", "## Environment", "", "```json", json.dumps(meta, indent=2, default=str), "```", ""]
    return "\n".join(lines)
