"""Weight bytes read per output byte, and the bandwidth-model time prediction (pure).

A component is read `calls_per_byte` times per generated byte (1 for per-byte local modules,
1/bytes_per_patch for the global model, 1/bytes_per_token for OLMo's layers). Its weight bytes
per call depend on the scheme:

  bf16     2 bytes per element
  int8_wo  1 byte per element + one bf16 scale per output row
  int4_wo  0.5 byte per element + one bf16 (scale, zero) pair per group of `group_size` inputs
           per output row (torchao tinygemm layout: `scales_and_zeros`, bf16 [K/g, N, 2])

Not counted: activations, recurrent state (about 40 MB read+written per byte, 4% of bf16 bytes),
KV cache. Biases and norms are `other_params`, counted at 2 bytes and never quantized. Embedding
tables count only the rows read per step.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

from .select import group_of, olmo_group_of, selects

BF16 = 2


@dataclass(frozen=True)
class Linear:
    out_features: int
    in_features: int
    group: str | None  # "local" | "global" | None (never quantized), from select.group_of


@dataclass(frozen=True)
class Component:
    name: str
    calls_per_byte: float
    linears: tuple[Linear, ...] = ()
    other_params: int = 0  # bf16 tensors read in full and never quantized
    kind: str = "local"  # reporting group: "local", "global", "head", "embed"


@dataclass(frozen=True)
class Variant:
    name: str
    target: str = "none"  # none | local | global | all
    scheme: str = "int8_wo"
    group_size: int = 128
    local_scheme: str | None = None  # per-group override of `scheme` (Bolmo)
    global_scheme: str | None = None


def linear_bytes(lin: Linear, scheme: str | None, group_size: int = 128) -> float:
    n = lin.out_features * lin.in_features
    if scheme is None:
        return n * BF16
    if scheme == "int8_wo":
        return n + lin.out_features * BF16
    if scheme == "int4_wo":
        if lin.in_features % group_size:
            raise ValueError(f"in_features {lin.in_features} not divisible by group_size {group_size}")
        groups = lin.in_features // group_size
        return n * 0.5 + lin.out_features * groups * 2 * BF16
    raise ValueError(f"unknown scheme {scheme!r}")


def component_bytes(c: Component, v: Variant | None) -> float:
    """Weight bytes read per call of the component under variant v (None = bf16)."""
    total = c.other_params * BF16
    for lin in c.linears:
        quant = v is not None and selects(v.target, lin.group)
        scheme = None
        if quant:
            scheme = (v.local_scheme if lin.group == "local" else v.global_scheme if lin.group == "global" else None) \
                or v.scheme
        total += linear_bytes(lin, scheme, v.group_size if v else 128)
    return total


def bytes_per_output_byte(components: list[Component], v: Variant | None = None) -> dict[str, float]:
    """Per component name, plus "total" and "kind:<kind>" sums."""
    out: dict[str, float] = {}
    for c in components:
        b = component_bytes(c, v) * c.calls_per_byte
        out[c.name] = b
        out[f"kind:{c.kind}"] = out.get(f"kind:{c.kind}", 0.0) + b
        out["total"] = out.get("total", 0.0) + b
    return out


@dataclass(frozen=True)
class Calibration:
    """Measured bf16 ms per output byte, split into weight-proportional and constant time.

    `ms_by_kind`: time that scales with the weight bytes of that kind ("local", "global", ...).
    `const_ms`: everything else (prefill, host loop), kept constant across variants.
    """

    ms_by_kind: dict[str, float]
    const_ms: float = 0.0

    @property
    def total_ms(self) -> float:
        return self.const_ms + sum(self.ms_by_kind.values())


def predict_ms(components: list[Component], cal: Calibration, v: Variant) -> float:
    """Time proportional to bytes read, per kind, calibrated on bf16; constant time unchanged."""
    base = bytes_per_output_byte(components, None)
    var = bytes_per_output_byte(components, v)
    ms = cal.const_ms
    for kind, t in cal.ms_by_kind.items():
        b0 = base.get(f"kind:{kind}", 0.0)
        ms += t * (var.get(f"kind:{kind}", 0.0) / b0) if b0 else t
    return ms


def _linears(linears_by_module: dict[str, tuple[int, int]], pattern: str, group=group_of) -> tuple[Linear, ...]:
    return tuple(Linear(o, i, group(n)) for n, (o, i) in linears_by_module.items() if re.match(pattern, n))


def bolmo_components(linears_by_module: dict[str, tuple[int, int]], other_params: dict[str, int],
                     bytes_per_patch: float, hidden: int, vocab_out: int, n_embed_rows: int = 2) -> list[Component]:
    """Bolmo's components from {linear module name: (out, in)} and {component name: other params}."""
    return [
        Component("local_encoder", 1.0, _linears(linears_by_module, r"model\.local_encoder\.(layers|out_projection)"),
                  other_params.get("local_encoder", 0), "local"),
        Component("local_decoder", 1.0, _linears(linears_by_module, r"model\.local_decoder\.(layers|in_projection)"),
                  other_params.get("local_decoder", 0), "local"),
        Component("global_model", 1.0 / bytes_per_patch, _linears(linears_by_module, r"model\.layers\."),
                  other_params.get("global_model", 0), "global"),
        Component("lm_head", 1.0, (Linear(vocab_out, hidden, None),), 0, "head"),
        Component("embeddings", 1.0, (), n_embed_rows * hidden, "embed"),
    ]


def olmo_components(linears_by_module: dict[str, tuple[int, int]], other_params: dict[str, int],
                    bytes_per_token: float, hidden: int, vocab: int) -> list[Component]:
    return [
        Component("layers", 1.0 / bytes_per_token, _linears(linears_by_module, r"model\.layers\.", olmo_group_of),
                  other_params.get("layers", 0), "global"),
        Component("lm_head", 1.0 / bytes_per_token, (Linear(vocab, hidden, "head"),), 0, "head"),
        Component("embeddings", 1.0 / bytes_per_token, (), hidden, "embed"),
    ]
