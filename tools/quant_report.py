"""Builds the tables of the `## Local-stack quantization` report from results/quant/*.

Run: python -X utf8 tools/quant_report.py > results/quant/report.md
Reads: results/quant/stage0.json (predictions), s4-<model>-<variant>-r{1,2}/breakdown.json (speed),
eval-<variant>-{bpb,cute}/eval.json (quality). Missing inputs are skipped, not invented.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from byteprof.counting import first_divergence  # noqa: E402
from byteprof.stats import paired_bootstrap_diff, paired_relative_change  # noqa: E402

Q = Path("results/quant")
BOLMO = ["bf16", "local-int8", "local-int4", "global-int4", "all-int4"]
PRETTY = {"bf16": "bf16", "local-int8": "local int8", "local-int4": "local int4", "global-int4": "global int4",
          "all-int4": "all int4"}
PROMPTS = ["prose_en", "code_py", "prose_de", "json_struct", "unicode_mix"]
PROMPT_SHORT = ["prose_en", "code_py", "prose_de", "json", "unicode"]


def load(path: Path):
    return json.loads(path.read_text(encoding="utf-8")) if path.is_file() else None


def latest(d: Path) -> Path | None:
    subs = sorted(p for p in d.glob("2*") if p.is_dir())
    return subs[-1] if subs else None


def speed(model: str, variant: str, rep: int):
    d = latest(Q / f"s4-{model}-{variant}-r{rep}")
    j = load(d / "breakdown.json") if d else None
    if not j:
        return None
    rows = j["rows"]
    ms = sum(r["ms"] for r in rows) / sum(r["new_bytes"] for r in rows)
    return {"ms_per_byte": ms, "bytes": sum(r["new_bytes"] for r in rows), "meta": j["meta"], "dir": str(d),
            "warnings": j.get("warnings", []), "outputs": load(d / "outputs.json")}


def fmt_div(variant_out: dict, bf16_out: dict) -> str:
    cells = []
    for p in PROMPTS:
        d = first_divergence(bf16_out[p].encode("utf-8"), variant_out[p].encode("utf-8"))
        cells.append("-" if d is None else str(d))
    return " / ".join(cells)


def main() -> None:
    s0 = load(Q / "stage0.json")
    out: list[str] = []
    base = {}
    out.append("### Speed (ms per generated byte = wall time / new bytes, no hooks, mean of 2 runs)")
    out.append("")
    out.append("| variant | run 1 | run 2 | diff | mean | weight MB/byte | predicted ms | measured reduction | predicted reduction "
               "| H11 window (+-30%) | peak MiB | first divergence vs bf16 (" + " / ".join(PROMPT_SHORT) + ") |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---|")
    results = {}
    for v in BOLMO:
        r = [speed("bolmo", v, k) for k in (1, 2)]
        if not all(r):
            continue
        results[v] = r
    bf = results.get("bf16")
    bf_mean = sum(x["ms_per_byte"] for x in bf) / 2 if bf else None
    for v, r in results.items():
        mean = sum(x["ms_per_byte"] for x in r) / 2
        diff = abs(r[0]["ms_per_byte"] - r[1]["ms_per_byte"]) / mean * 100
        name = PRETTY[v]
        s = s0["bolmo"][name] if s0 and name in s0["bolmo"] else None
        wmb = s["bytes"]["total"] / 1e6 if s else float("nan")
        pred = s["pred_ms"] if s else float("nan")
        red = (bf_mean - mean) if bf_mean else float("nan")
        pred_red = (bf_mean - pred) if bf_mean else float("nan")
        win = "n/a"
        if v != "bf16" and bf_mean:
            lo, hi = 0.7 * pred_red, 1.3 * pred_red
            win = f"{'inside' if lo <= red <= hi else 'OUTSIDE'} [{lo:.3f}, {hi:.3f}] ms"
        peak = r[0]["meta"]["optimization"]["gpu_mem_peak_mib"]
        div = "-" if v == "bf16" or not bf else fmt_div(r[0]["outputs"], bf[0]["outputs"])
        out.append(f"| {name} | {r[0]['ms_per_byte']:.3f} | {r[1]['ms_per_byte']:.3f} | {diff:.1f}% | **{mean:.3f}** | "
                   f"{wmb:.1f} | {pred:.3f} | {red:.3f} ms ({red / bf_mean * 100:.1f}%) | {pred_red:.3f} ms "
                   f"({pred_red / bf_mean * 100:.1f}%) | {win} | {peak:.0f} | {div} |")
    # H14
    if bf_mean and "local-int4" in results and "global-int4" in results:
        gb = {"local": 0.358, "global": 2.147}
        sav = {}
        for t in ("local", "global"):
            m = sum(x["ms_per_byte"] for x in results[f"{t}-int4"]) / 2
            sav[t] = (bf_mean - m, (bf_mean - m) / gb[t])
        out += ["", "### H14: ms saved per GB of bf16 weights quantized (int4 g128)", "",
                "| target | ms saved per byte | stored bf16 weights quantized | ms saved per GB |", "|---|---:|---:|---:|"]
        for t in ("local", "global"):
            out.append(f"| {t} | {sav[t][0]:.3f} | {gb[t]:.3f} GB | {sav[t][1]:.3f} |")
        out.append(f"\nratio local / global = **{sav['local'][1] / sav['global'][1]:.2f}x** "
                   f"(prediction in Stage 0: {s0['h14_int4_wo']['ratio']:.2f}x; hypothesis threshold 2x)")
    # OLMo
    ol = {v: [speed("olmo", v, k) for k in (1, 2)] for v in ("bf16", "all-int4")}
    if all(all(x) for x in ol.values()):
        out += ["", "### OLMo 2 1B (compiled, minimal loop, 72 tokens ~ 256 bytes), ms per generated byte", "",
                "| variant | run 1 | run 2 | diff | mean | Bolmo mean | Bolmo / OLMo |", "|---|---:|---:|---:|---:|---:|---:|"]
        for v, r in ol.items():
            mean = sum(x["ms_per_byte"] for x in r) / 2
            b = results.get("bf16" if v == "bf16" else "all-int4")
            bm = sum(x["ms_per_byte"] for x in b) / 2 if b else float("nan")
            out.append(f"| {v} | {r[0]['ms_per_byte']:.3f} | {r[1]['ms_per_byte']:.3f} | "
                       f"{abs(r[0]['ms_per_byte'] - r[1]['ms_per_byte']) / mean * 100:.1f}% | {mean:.3f} | {bm:.3f} | {bm / mean:.2f}x |")
    # quality
    out += ["", "### Quality (same quantized weights as the speed runs)", "",
            "| variant | bpb (95% CI) | bpb change vs bf16 (paired 95% CI) | marginal bpb | CUTE acc (95% CI) | CUTE diff vs bf16, points (paired 95% CI) |",
            "|---|---:|---:|---:|---:|---:|"]
    bb = load(Q / "eval-bf16-bpb/eval.json")
    bc = load(Q / "eval-bf16-cute/eval.json")
    for v in BOLMO:
        b = load(Q / f"eval-{v}-bpb/eval.json")
        c = load(Q / f"eval-{v}-cute/eval.json")
        cells = [PRETTY[v]]
        if b:
            r = b["result"]
            cells.append(f"{r['bpb']:.4f} ({r['bpb_ci95'][0]:.4f}-{r['bpb_ci95'][1]:.4f})")
            if bb and v != "bf16":
                pa = [(x["bits_fused"], x["bytes"]) for x in r["chunks"]]
                pb = [(x["bits_fused"], x["bytes"]) for x in bb["result"]["chunks"]]
                ch, lo, hi = paired_relative_change(pa, pb)
                cells.append(f"{ch * 100:+.2f}% ({lo * 100:+.2f}% to {hi * 100:+.2f}%)")
            else:
                cells.append("-")
            cells.append(f"{r['bpb_marginal']:.4f}")
        else:
            cells += ["n/a", "n/a", "n/a"]
        if c:
            r = c["result"]
            cells.append(f"{r['accuracy'] * 100:.1f}% ({r['accuracy_ci95'][0] * 100:.1f}-{r['accuracy_ci95'][1] * 100:.1f})")
            if bc and v != "bf16":
                a = [float(x["correct"]) for x in r["items"]]
                z = [float(x["correct"]) for x in bc["result"]["items"]]
                d, lo, hi = paired_bootstrap_diff(a, z)
                cells.append(f"{d * 100:+.1f} ({lo * 100:+.1f} to {hi * 100:+.1f})")
            else:
                cells.append("-")
        else:
            cells += ["n/a", "n/a"]
        out.append("| " + " | ".join(cells) + " |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
