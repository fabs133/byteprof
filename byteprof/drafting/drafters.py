"""Drafters (pure Python): context lookup, oracle, combined, none. The n-gram drafter is in ngram.py.

Interface (see sim.Drafter): `reset(ctx_atoms, truth)` with the prompt atoms followed by a_0,
`propose(k)` -> up to k atoms that continue the context, `push(atoms)` with the atoms a round emitted.
An atom is `byte | flag << 8`; for text that is already in the context the flag is the recorded one
(prefill boundary mask for the prompt, the generated flag for generated bytes).
"""

from __future__ import annotations

from collections.abc import Sequence


class NullDrafter:
    name = "none"

    def reset(self, ctx_atoms: Sequence[int], truth: Sequence[int] | None = None) -> None:
        pass

    def propose(self, k: int) -> list[int]:
        return []

    def push(self, atoms: Sequence[int]) -> None:
        pass


class OracleDrafter:
    """The true next atoms (upper bound only; needs the recorded ground truth)."""

    name = "oracle"

    def __init__(self) -> None:
        self.truth: Sequence[int] = []
        self.i = 0

    def reset(self, ctx_atoms: Sequence[int], truth: Sequence[int] | None = None) -> None:
        if truth is None:
            raise ValueError("the oracle drafter needs the ground-truth atoms")
        self.truth, self.i = truth, 0  # truth[0] is a_0, the last atom of the context

    def propose(self, k: int) -> list[int]:
        return list(self.truth[self.i + 1: self.i + 1 + k])

    def push(self, atoms: Sequence[int]) -> None:
        self.i += len(atoms)


class ContextDrafter:
    """Prompt-lookup: find the longest earlier occurrence of the context's suffix (at least `min_len`
    bytes) and propose what followed it. A continuation that runs into the end of the context keeps
    going periodically (it reads the draft it has already produced)."""

    name = "context"

    def __init__(self, min_len: int = 4, max_candidates: int = 8, max_match: int = 64):
        self.min_len, self.max_cand, self.max_match = min_len, max_candidates, max_match
        self.buf = bytearray()
        self.flags = bytearray()
        self.index: dict[bytes, list[int]] = {}
        self.last_match = 0

    def reset(self, ctx_atoms: Sequence[int], truth: Sequence[int] | None = None) -> None:
        self.buf, self.flags, self.index = bytearray(), bytearray(), {}
        self.push(ctx_atoms)

    def push(self, atoms: Sequence[int]) -> None:
        buf, flags, index, m = self.buf, self.flags, self.index, self.min_len
        for a in atoms:
            buf.append(a & 255)
            flags.append(a >> 8)
            n = len(buf)
            if n >= m:
                index.setdefault(bytes(buf[n - m:n]), []).append(n - 1)

    def find(self) -> tuple[int, int]:
        """(end index of the best earlier match, match length) or (-1, 0)."""
        buf = self.buf
        n = len(buf)
        if n < self.min_len:
            return -1, 0
        cands = self.index.get(bytes(buf[n - self.min_len:n]))
        if not cands:
            return -1, 0
        best_e, best_l = -1, 0
        seen = 0
        for e in reversed(cands):
            if e == n - 1:
                continue
            seen += 1
            if seen > self.max_cand:
                break
            l = 0
            cap = min(self.max_match, e + 1)
            while l < cap and buf[e - l] == buf[n - 1 - l]:
                l += 1
            if l > best_l:
                best_e, best_l = e, l
        return best_e, best_l

    def propose(self, k: int) -> list[int]:
        e, l = self.find()
        self.last_match = l
        if e < 0 or k <= 0:
            return []
        buf, flags = self.buf, self.flags
        n = len(buf)
        out: list[int] = []
        for t in range(k):
            idx = e + 1 + t
            if idx < n:
                out.append(buf[idx] | (flags[idx] << 8))
            else:
                out.append(out[idx - n])
        return out


class CombinedDrafter:
    """`context` when it finds a match of at least `min_len` bytes, otherwise `ngram`."""

    name = "combined"

    def __init__(self, context: ContextDrafter, ngram) -> None:
        self.context, self.ngram = context, ngram
        self.used_context = 0
        self.used_ngram = 0

    def reset(self, ctx_atoms: Sequence[int], truth: Sequence[int] | None = None) -> None:
        self.context.reset(ctx_atoms, truth)
        self.ngram.reset(ctx_atoms, truth)

    def push(self, atoms: Sequence[int]) -> None:
        self.context.push(atoms)
        self.ngram.push(atoms)

    def propose(self, k: int) -> list[int]:
        d = self.context.propose(k)
        if d:
            self.used_context += 1
            return d
        self.used_ngram += 1
        return self.ngram.propose(k)
