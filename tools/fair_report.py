from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, str(Path(__file__).resolve().parent))

import byte_accounting as ba  # noqa: E402
from byteprof.counting import first_divergence  # noqa: E402
from byteprof.evaluate import CUTE_ITEMS, CUTE_SEED  # noqa: E402
from byteprof.quant.accounting import Variant, bytes_per_output_byte, bolmo_components, olmo_components  # noqa: E402
from byteprof.stats import paired_bootstrap_diff, paired_relative_change, stratified_sample  # noqa: E402

R = Path("results/fair")
BOLMO = {  # name -> accounting variant
    "bf16": Variant("bf16"),
    "local-int8": Variant("local int8", "local", "int8_wo"),
    "local-int4": Variant("local int4", "local", "int4_wo"),
    "global-int4": Variant("global int4", "global", "int4_wo"),
    "all-int4": Variant("all int4", "all", "int4_wo"),
    "global-int8": Variant("global int8", "global", "int8_wo"),
    "all-int8": Variant("all int8", "all", "int8_wo"),
    "l4g8": Variant("local int4 + global int8", "all", "int4_wo", 128, global_scheme="int8_wo"),
}
OLMO = {
    "bf16": Variant("bf16"),
    "int4-blocks": Variant("int4 blocks", "blocks", "int4_wo"),
    "int4-blocks-head": Variant("int4 blocks+head", "blocks+head", "int4_wo"),
    "int8-blocks": Variant("int8 blocks", "blocks", "int8_wo"),
}
PROMPTS = ["prose_en", "code_py", "prose_de", "json_struct", "unicode_mix"]


def load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def latest(d: Path):
    subs = sorted(p for p in d.glob("2*") if p.is_dir())
    return subs[-1] if subs else None


def speed(model: str, v: str, rep: int):
    d = latest(R / f"s-{model}-{v}-r{rep}")
    j = load(d / "breakdown.json") if d else None
    if not j:
        return None
    rows = j["rows"]
    return {"ms": sum(r["ms"] for r in rows) / sum(r["new_bytes"] for r in rows), "outputs": load(d / "outputs.json"),
            "peak": j["meta"]["optimization"]["gpu_mem_peak_mib"], "div_self": [r["first_divergence"] for r in rows]}


def fit(x, y):
    A = np.vstack([np.ones(len(x)), x]).T
    (a, k), *_ = np.linalg.lstsq(A, np.array(y), rcond=None)
    res = np.array(y) - (a + k * np.array(x))
    ss = float(((np.array(y) - np.mean(y)) ** 2).sum())
    return float(a), float(k), res, 1 - float((res ** 2).sum()) / ss if ss else float("nan")


def main() -> None:
    mb, lb = ba.shapes(*ba.BOLMO)
    comps_b = bolmo_components(lb, ba.other_params(mb, lb, ba.bolmo_owner), ba.BYTES_PER_PATCH, 2048, 520)
    mo, lo = ba.shapes(*ba.OLMO)
    comps_o = olmo_components(lo, ba.other_params(mo, lo, ba.olmo_owner), ba.BYTES_PER_TOKEN, 2048, 100352)
    out: list[str] = []
    data = {}
    for model, variants, comps in (("bolmo", BOLMO, comps_b), ("olmo", OLMO, comps_o)):
        out += [f"### Speed: {model} (ms per generated byte = wall / new bytes; no hooks; 2 runs)", "",
                "| variant | run 1 | run 2 | diff | **mean** | weight MB/byte | peak MiB | first divergence vs bf16 (" +
                " / ".join(PROMPTS) + ") |", "|---|---:|---:|---:|---:|---:|---:|---|"]
        base = None
        for v, acc in variants.items():
            r = [speed(model, v, k) for k in (1, 2)]
            if not all(r):
                out.append(f"| {v} | missing | | | | | | |")
                continue
            mean = (r[0]["ms"] + r[1]["ms"]) / 2
            wmb = bytes_per_output_byte(comps, acc)["total"] / 1e6
            if v == "bf16":
                base = r[0]["outputs"]
            div = "-"
            if v != "bf16" and base:
                div = " / ".join("-" if (d := first_divergence(base[p].encode(), r[0]["outputs"][p].encode())) is None
                                 else str(d) for p in PROMPTS)
            out.append(f"| {v} | {r[0]['ms']:.3f} | {r[1]['ms']:.3f} | {abs(r[0]['ms'] - r[1]['ms']) / mean * 100:.1f}% | "
                       f"**{mean:.3f}** | {wmb:.1f} | {r[0]['peak']:.0f} | {div} |")
            data[(model, v)] = (mean, wmb)
        out.append("")
    # ratios
    out += ["### Bolmo / OLMo 2 ratios (same session, same kernels, graph + minimal loop)", "",
            "| precision | Bolmo variant | Bolmo | OLMo variant | OLMo | ratio |", "|---|---|---:|---|---:|---:|"]
    pairs = [("bf16", "bf16", "bf16"), ("int8 (blocks int8, Bolmo all int8)", "all-int8", "int8-blocks"),
             ("int4, blocks only (OLMo head bf16)", "all-int4", "int4-blocks"),
             ("int4, OLMo head also int4", "all-int4", "int4-blocks-head")]
    for label, bv, ov in pairs:
        if ("bolmo", bv) in data and ("olmo", ov) in data:
            b, o = data[("bolmo", bv)][0], data[("olmo", ov)][0]
            out.append(f"| {label} | {bv} | {b:.3f} | {ov} | {o:.3f} | **{b / o:.2f}x** |")
    # fits
    out += ["", "### Fit: ms/byte = fixed + k x weight MB/byte", ""]
    for model in ("bolmo", "olmo"):
        pts = [(w, m, v) for (mo_, v), (m, w) in data.items() if mo_ == model]
        if len(pts) >= 3:
            a, k, res, r2 = fit([p[0] for p in pts], [p[1] for p in pts])
            out.append(f"- **{model}** ({len(pts)} variants): fixed = **{a:.3f} ms/byte**, k = {k * 1000:.3f} ms per GB/byte, "
                       f"R^2 = {r2:.4f}; residuals (ms): " + ", ".join(f"{p[2]} {r:+.3f}" for p, r in zip(pts, res)))
    # quality
    out += ["", "### Quality (Bolmo: bpb of fused tokens; OLMo: token NLL; only within-model deltas are meaningful)", "",
            "| model | variant | bpb (95% CI) | bpb change vs own bf16 (paired CI) | CUTE-1500 (95% CI) | CUTE-1500 diff, points (paired CI) "
            "| CUTE old-500 subset | old-500 diff (paired CI) |", "|---|---|---:|---:|---:|---:|---:|---:|"]
    sizes = {t: 1000 for t in range(14)}
    base500 = None
    for model, names in (("bolmo", ["bf16", "local-int4", "global-int8", "all-int8", "l4g8"]),
                         ("olmo", ["bf16", "int4-blocks", "int4-blocks-head", "int8-blocks"])):
        bb = load(R / f"eval-{model}-bf16-bpb/eval.json")
        bc = load(R / f"eval-{model}-bf16-cute/eval.json")
        for v in names:
            b = load(R / f"eval-{model}-{v}-bpb/eval.json")
            c = load(R / f"eval-{model}-{v}-cute/eval.json")
            cells = [model, v]
            if b:
                r = b["result"]
                cells.append(f"{r['bpb']:.4f} ({r['bpb_ci95'][0]:.4f}-{r['bpb_ci95'][1]:.4f})")
                if bb and v != "bf16":
                    ch, lo_, hi_ = paired_relative_change([(x["bits_fused"], x["bytes"]) for x in r["chunks"]],
                                                          [(x["bits_fused"], x["bytes"]) for x in bb["result"]["chunks"]])
                    cells.append(f"{ch * 100:+.2f}% ({lo_ * 100:+.2f} to {hi_ * 100:+.2f})")
                else:
                    cells.append("-")
            else:
                cells += ["n/a", "n/a"]
            if c:
                items = c["result"]["items"]
                task_names = sorted({x["task"] for x in items})
                pick = stratified_sample({t: 1000 for t in task_names}, CUTE_ITEMS, CUTE_SEED)
                in500 = [x["index"] in set(pick[x["task"]]) for x in items]
                acc = c["result"]
                cells.append(f"{acc['accuracy'] * 100:.1f}% ({acc['accuracy_ci95'][0] * 100:.1f}-{acc['accuracy_ci95'][1] * 100:.1f}), n={len(items)}")
                a_all = [float(x["correct"]) for x in items]
                a_500 = [float(x["correct"]) for x, f in zip(items, in500) if f]
                if bc and v != "bf16":
                    z_all = [float(x["correct"]) for x in bc["result"]["items"]]
                    z_500 = [float(x["correct"]) for x, f in zip(bc["result"]["items"], in500) if f]
                    d, lo_, hi_ = paired_bootstrap_diff(a_all, z_all)
                    cells.append(f"{d * 100:+.1f} ({lo_ * 100:+.1f} to {hi_ * 100:+.1f})")
                    cells.append(f"{sum(a_500) / len(a_500) * 100:.1f}% (n={len(a_500)})")
                    d5, l5, h5 = paired_bootstrap_diff(a_500, z_500)
                    cells.append(f"{d5 * 100:+.1f} ({l5 * 100:+.1f} to {h5 * 100:+.1f})")
                else:
                    cells += ["-", f"{sum(a_500) / len(a_500) * 100:.1f}% (n={len(a_500)})", "-"]
            else:
                cells += ["n/a"] * 4
            out.append("| " + " | ".join(cells) + " |")
    print("\n".join(out))


if __name__ == "__main__":
    main()
